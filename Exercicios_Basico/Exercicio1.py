numero1 = float(input("Digite o numero A:"))
numero2 = float(input("Digite o numero B:"))

soma = numero1 + numero2
sub = numero1 - numero2
mult = numero1 * numero2
div = numero1 / numero2
print("\n-----Resultados-----\n")
print(numero1, "+", numero2, " =", soma, "\n" )
print(numero1, "-", numero2, " =", sub, "\n" )
print(numero1, ".", numero2, " =", mult, "\n" )
print(numero1, "/", numero2, " =", div, "\n" )